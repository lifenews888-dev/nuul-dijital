/**
 * Бүртгэлийн үйлдлийн монгол нэрс — `admin.html:857`-ийн `ACTN`.
 *
 * admin.html нь хоёр хувилбартай: `ACTN` («Нийтлэв», «Төлөв солив» —
 * бүртгэлийн мөрт) ба `ACTW` («нийтлэв», «сайтаас буулгав» — «Болд
 * нийтлэв» гэх урсгал өгүүлбэрт). Бид ХОЁУЛАНГААС нь өөр хэлбэр авна:
 * `-сан` нөхцөлтэй («Нийтэлсэн», «Сайтаас буулгасан»). Шалтгаан нь мөрийн
 * бүтэц: «Нийтэлсэн · Болд» гэдэг нь үйлдлийг нэр мэт уншуулна, artifact
 * нь үйл үгийн төгсгөх хэлбэрийг хэрэглэдэг тул «Нийтлэв · Болд» гэж
 * уншихад хоёр өгүүлбэр шиг сална.
 */
export const ACTION_LABELS: Record<string, string> = {
  create: "Үүсгэсэн",
  save: "Хадгалсан",
  submit: "Хянуулахаар илгээсэн",
  approve: "Баталсан",
  return: "Буцаасан",
  publish: "Нийтэлсэн",
  unpublish: "Сайтаас буулгасан",
  status: "Төлөв өөрчилсөн",
  delete: "Устгасан",
};

/**
 * `NewsActivity.action` нь чөлөөт тэмдэгт мөр тул танихгүй утга орж ирж
 * болно — хуучин мөр, дараа нэмэгдэх үйлдэл, гараар оруулсан өгөгдөл.
 * Тэр үед ТҮҮХИЙ нэрээр нь харуулна: бүртгэлийн мөр хоосон байх нь
 * «юу ч болоогүй» гэсэн ХУДАЛ хариулт болно.
 */
export function actionLabel(action: string): string {
  const key = action.trim();
  if (!key) return "Үйлдэл";
  return ACTION_LABELS[key] ?? key;
}
