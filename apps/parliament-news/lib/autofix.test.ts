import { describe, it, expect } from "vitest";
import { autoFix } from "./autofix";

/**
 * admin.html-ийн `autoFix` — бичих зуурт зай, цэг таслал, хашилтыг
 * цэгцлэнэ. Редактор яаран бичихэд үлддэг жижиг согогууд: давхар зай,
 * цэгийн өмнөх зай, англи хашилт.
 *
 * ДОГОЛ МӨРИЙГ ХАДГАЛНА: нийтийн нийтлэлийн хуудас биетийг хоосон
 * мөрөөр догол мөр болгон хуваадаг (`lib/article.ts`-ийн `paragraphs`).
 * Хоосон мөрийг цэвэрлэвэл бүх мэдээ нэг урт блок болно.
 */
describe("autoFix", () => {
  it("давхар зайг нэг болгоно", () => {
    expect(autoFix("а  б")).toBe("а б");
    expect(autoFix("а     б")).toBe("а б");
  });

  it("цэг таслалын өмнөх зайг хасна", () => {
    expect(autoFix("а , б")).toBe("а, б");
    expect(autoFix("тийм .")).toBe("тийм.");
  });

  it("цэг таслалын дараа зай тавина", () => {
    expect(autoFix("а,б")).toBe("а, б");
    expect(autoFix("нэг.хоёр")).toBe("нэг. хоёр");
  });

  it("тоонуудын хооронд цэг тавихгүй — 2026.11.27 хэвээр", () => {
    expect(autoFix("2026.11.27")).toBe("2026.11.27");
    expect(autoFix("40,5 хувь")).toBe("40,5 хувь");
  });

  it("монгол хашилт болгоно", () => {
    expect(autoFix('"үг"')).toBe("«үг»");
    expect(autoFix('Тэр "сайн" гэв')).toBe("Тэр «сайн» гэв");
  });

  it("гурван цэгийг нэг тэмдэг болгоно", () => {
    expect(autoFix("тэгээд...")).toBe("тэгээд…");
  });

  /** Хамгийн чухал нь: догол мөр эвдэрвэл БҮХ мэдээ нэг блок болно */
  it("догол мөрийг ХАДГАЛНА", () => {
    expect(autoFix("Нэг дэх.\n\nХоёр дахь.")).toBe("Нэг дэх.\n\nХоёр дахь.");
  });

  it("гурав ба түүнээс дээш хоосон мөрийг хоёр болгоно", () => {
    expect(autoFix("а\n\n\n\nб")).toBe("а\n\nб");
  });

  it("мөрийн эхэн, төгсгөлийн зайг хасна", () => {
    expect(autoFix("  а  ")).toBe("а");
    expect(autoFix("а  \n  б")).toBe("а\nб");
  });

  it("хоосон текстэд хоосон", () => {
    expect(autoFix("")).toBe("");
    expect(autoFix("   ")).toBe("");
  });

  it("зөв бичсэн текстийг ХӨНДӨХГҮЙ", () => {
    const good = "Улсын Их Хурал өнөөдөр хуралдлаа.\n\nТөсвийн тухай хуулийг хэлэлцэв.";
    expect(autoFix(good)).toBe(good);
  });
});
